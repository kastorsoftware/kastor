// returns estimated registration timestamp (unix seconds) for a given user_id.
// uses linear interpolation between nearest anchor points.
pub fn estimate_registration_ts(user_id: i64) -> i64 {
    if user_id <= 0 {
        return 0;
    }

    let len = ANCHORS.len();
    if len == 0 {
        return 0;
    }

    if user_id <= ANCHORS[0].0 {
        return ANCHORS[0].1;
    }

    if user_id >= ANCHORS[len - 1].0 {
        return ANCHORS[len - 1].1;
    }

    // binary search for the interval
    let mut lo = 0;
    let mut hi = len - 1;
    while lo + 1 < hi {
        let mid = (lo + hi) / 2;
        if ANCHORS[mid].0 <= user_id {
            lo = mid;
        } else {
            hi = mid;
        }
    }

    let (id_lo, ts_lo) = ANCHORS[lo];
    let (id_hi, ts_hi) = ANCHORS[hi];

    if id_hi == id_lo {
        return ts_lo;
    }

    let ratio = (user_id - id_lo) as f64 / (id_hi - id_lo) as f64;
    let ts = ts_lo as f64 + ratio * (ts_hi - ts_lo) as f64;
    ts as i64
}
